"""Reproducible rendered sequences: views, disappearance, object motion and pitch.

Robot poses are prescribed, not generated by a locomotion controller.
Ground truth is used only for scoring after RGB-D inference.
"""

import argparse
import json
from pathlib import Path
import tempfile

from evaluate_perception import initialize_renderer, reference, visible_reference
import cv2
import mujoco
import numpy as np
import yaml

from g1_backend.camera_control import tilted_quaternion
from g1_backend.config import ROOT, load_config
from g1_backend.perception import Settings
from g1_backend.perception_rgbd import detect_instances
from g1_backend.perception_tracking import Tracker, TrackingSettings
from g1_backend.perception_views import ViewAccumulator
from g1_backend.perception_yolo import YoloSegmenter
from g1_backend.sensor_effects import SensorEffects
from g1_backend.simulator import model_xml


def sequence():
    steps = []

    def add(stage, count, **values):
        steps.extend(dict(stage=stage, **values) for _ in range(count))

    add('stationary', 6, distance=0.9)
    for distance in np.linspace(0.9, 0.6, 6):
        add('approach', 1, distance=float(distance))
    for bearing in np.linspace(-15, 15, 9):
        add('turn', 1, bearing=float(bearing))
    add('settle', 6)
    add('brief_loss', 2, away=True)
    add('brief_recovery', 6)
    add('long_loss', 6, away=True)
    add('long_recovery', 6)
    for displacement in np.linspace(0.025, 0.125, 5):
        add('object_motion', 1, displacement=float(displacement))
    add('object_settle', 7, displacement=0.125)
    return steps


def run(args):
    initialize_renderer()
    config = load_config(ROOT / 'configs/experiments/navigation.yaml')
    config['camera']['width'], config['camera']['height'] = 424, 240
    sources = model_xml(config)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory)
        (path / 'g1_29dof.xml').write_text(sources[0])
        (path / 'scene.xml').write_text(sources[1])
        model = mujoco.MjModel.from_xml_path(str(path / 'scene.xml'))
    data = mujoco.MjData(model)
    deployment = yaml.safe_load((ROOT / config['locomotion']['deployment']).read_text())
    for actuator, position in zip(
        deployment['joint_ids_map'], deployment['default_joint_pos'], strict=True
    ):
        data.qpos[model.jnt_qposadr[model.actuator_trnid[actuator, 0]]] = position
    parameters = yaml.safe_load((ROOT / 'configs/perception.yaml').read_text())['g1_perception'][
        'ros__parameters'
    ]
    settings = Settings(
        **{k: v for k, v in parameters.items() if k in Settings.__dataclass_fields__}
    )
    tracking_settings = TrackingSettings(
        **{
            k.removeprefix('tracking.'): v
            for k, v in parameters.items()
            if k.startswith('tracking.')
        }
    )
    segmenter = YoloSegmenter(args.model, 0.3)
    camera = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_CAMERA, 'd435i')
    original = model.cam_quat[camera].copy()
    root = model.jnt_qposadr[
        model.body_jntadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, 'pelvis')]
    ]
    red_body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, 'red_cube')
    yellow_body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, 'yellow_box')
    red_address = model.jnt_qposadr[model.body_jntadr[red_body]]
    red_original = data.qpos[red_address : red_address + 3].copy()
    geoms = {
        'red_cube': int(model.body_geomadr[red_body]),
        'yellow_box': int(model.body_geomadr[yellow_body]),
    }
    noise = yaml.safe_load((ROOT / 'configs/navigation/sensors_real.yaml').read_text())
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    f = 240 / (2 * np.tan(np.deg2rad(model.cam_fovy[camera]) / 2))
    k = [f, 0, 211.5, 0, f, 119.5, 0, 0, 1]
    report = {
        'limits': [
            'Prescribed robot poses, not locomotion or Nav2.',
            'Image noise only; no ROS latency or real sensor calibration.',
        ],
        'profiles': {},
        'depth_pitch': [],
    }
    with mujoco.Renderer(model, height=240, width=424) as renderer:

        def render(distance=0.6, bearing=0, away=False, displacement=0, pitch=0, origin=False):
            theta = np.deg2rad(bearing)
            position = [4.5 + distance * np.sin(theta), -5 - distance * np.cos(theta), 0.793]
            yaw = np.pi / 2 + theta + (np.pi if away else 0)
            if origin:
                position, yaw = [0, 0, 0.793], 0
            data.qpos[root : root + 3] = position
            data.qpos[root + 3 : root + 7] = [np.cos(yaw / 2), 0, 0, np.sin(yaw / 2)]
            data.qpos[red_address : red_address + 3] = red_original + [displacement, 0, 0]
            model.cam_quat[camera] = tilted_quaternion(original, pitch)
            mujoco.mj_forward(model, data)
            renderer.update_scene(data, camera=camera)
            rgb = renderer.render().copy()
            renderer.enable_depth_rendering()
            depth = renderer.render().copy()
            renderer.disable_depth_rendering()
            renderer.enable_segmentation_rendering()
            labels = renderer.render().copy()
            renderer.disable_segmentation_rendering()
            pose = np.eye(4)
            pose[:3, :3] = data.cam_xmat[camera].reshape(3, 3) @ np.diag([1, -1, -1])
            pose[:3, 3] = data.cam_xpos[camera]
            return rgb, depth, labels, pose

        for profile in ['ideal', 'noise']:
            tracker, views = Tracker(tracking_settings), ViewAccumulator()
            effects = SensorEffects(noise, 42)
            records = []
            for index, step in enumerate(sequence()):
                values = {key: value for key, value in step.items() if key != 'stage'}
                rgb, depth, labels, pose = render(**values)
                sensors = {'d435i_rgb': rgb, 'd435i_depth': depth}
                if profile == 'noise':
                    sensors = effects.camera(sensors)
                raw = detect_instances(
                    sensors['d435i_depth'],
                    sensors['d435i_rgb'],
                    k,
                    segmenter.predict(sensors['d435i_rgb']),
                    pose,
                    settings=settings,
                )
                tracked = views.update(tracker.update(raw, index * 0.5), pose, index * 0.5)
                boxes = [
                    obj
                    for table in tracked
                    for obj in table['objects']
                    if obj['kind'] == 'box_candidate'
                ]
                references = {
                    name: reference(model, data, gid, name) for name, gid in geoms.items()
                }
                matches, used = {}, set()
                for name, truth in references.items():
                    candidates = [
                        (np.linalg.norm(np.array(obj['center']) - truth['center']), j, obj)
                        for j, obj in enumerate(boxes)
                        if j not in used
                    ]
                    nearest = (
                        min(candidates, key=lambda candidate: candidate[0]) if candidates else None
                    )
                    if nearest and nearest[0] < 0.2:
                        error, j, obj = nearest
                        used.add(j)
                        matches[name] = {
                            'id': obj['id'],
                            'error_m': float(error),
                            'stable': obj['stable'],
                            'reasons': obj['stability']['reasons'],
                            'views': obj['quality']['view_count'],
                        }
                records.append(
                    {
                        'stage': step['stage'],
                        'time': index * 0.5,
                        'visible_pixels': {
                            name: visible_reference(model, data, gid, labels)
                            for name, gid in geoms.items()
                        },
                        'matches': matches,
                        'extra_candidates': len(boxes) - len(used),
                    }
                )
            stages = {}
            for stage in dict.fromkeys(row['stage'] for row in records):
                rows = [row for row in records if row['stage'] == stage]
                red = [row['matches']['red_cube'] for row in rows if 'red_cube' in row['matches']]
                stages[stage] = {
                    'frames': len(rows),
                    'red_matches': len(red),
                    'stable_red': sum(obj['stable'] for obj in red),
                    'red_ids': sorted({obj['id'] for obj in red}),
                    'extra_candidates': sum(row['extra_candidates'] for row in rows),
                }
            report['profiles'][profile] = {'stages': stages, 'records': records}
        for origin in [False, True]:
            for pitch in [-30, -15, 0, 15, 30, 45]:
                rgb, depth, _, _ = render(pitch=pitch, origin=origin)
                measured = SensorEffects(noise, 42).camera({'d435i_depth': depth})['d435i_depth']
                valid = np.isfinite(measured) & (measured > 0)
                row = {
                    'location': 'origin' if origin else 'table',
                    'pitch_deg': pitch,
                    'ideal_min_m': float(depth.min()),
                    'ideal_max_m': float(depth.max()),
                    'valid_fraction': float(valid.mean()),
                    'valid_min_m': float(measured[valid].min()) if valid.any() else None,
                    'valid_max_m': float(measured[valid].max()) if valid.any() else None,
                }
                report['depth_pitch'].append(row)
                cv2.imwrite(
                    str(output / f'depth_{row["location"]}_{pitch}_rgb.png'),
                    cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR),
                )
                np.savez_compressed(
                    output / f'depth_{row["location"]}_{pitch}.npz',
                    depth=measured,
                    ideal_depth=depth,
                )
    report['checks'] = {}
    for name, profile in report['profiles'].items():
        records = profile['records']

        def red(stage, records=records):
            return [row['matches'].get('red_cube') for row in records if row['stage'] == stage]

        before = [obj for obj in red('settle') if obj]
        brief = [obj for obj in red('brief_recovery') if obj]
        long = [obj for obj in red('long_recovery') if obj]
        checks = {
            'stable_when_stationary': any(obj and obj['stable'] for obj in red('stationary')),
            'no_ghost_on_loss': all(
                obj is None for stage in ['brief_loss', 'long_loss'] for obj in red(stage)
            ),
            'brief_loss_preserves_id': bool(
                before and brief and before[-1]['id'] == brief[0]['id']
            ),
            'long_loss_changes_id': bool(brief and long and brief[-1]['id'] != long[0]['id']),
            'motion_rejects_stability': all(
                obj and not obj['stable'] for obj in red('object_motion')
            ),
            'stable_after_object_settles': bool(
                red('object_settle')[-1] and red('object_settle')[-1]['stable']
            ),
        }
        report['checks'][name] = checks
    (output / 'evaluation.json').write_text(json.dumps(report, indent=2, allow_nan=False))
    if not all(passed for checks in report['checks'].values() for passed in checks.values()):
        raise AssertionError('Dynamic perception check failed; inspect evaluation.json')
    print(
        json.dumps(
            {
                'checks': report['checks'],
                'profiles': {name: value['stages'] for name, value in report['profiles'].items()},
                'depth_pitch': report['depth_pitch'],
            },
            indent=2,
        )
    )


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', default='assets/perception/g1_objects_yolo11n_seg.onnx')
    parser.add_argument('--output', default='results/perception/dynamic_evaluation')
    run(parser.parse_args())
